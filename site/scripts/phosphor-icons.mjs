// Copies the Phosphor icons the site uses (MIT, @phosphor-icons/core) into src/icons.gen.ts as path data, so pages build them
// with the s() helper: no innerHTML, no extra request, nothing unused shipped. Run after changing ICONS:  npm run icons
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** name -> weights used */
const ICONS = {
  "arrow-right": ["regular"], "arrow-square-out": ["regular"], "caret-down": ["bold"], "caret-left": ["bold"], "caret-right": ["bold"],
  "caret-up": ["bold"], "chart-line-up": ["regular"], "check-circle": ["fill"], "copy": ["regular"], 
  "gauge": ["regular"], "github-logo": ["regular"], "house": ["fill"], "lightning": ["regular"], "list": ["regular"],
  "list-checks": ["regular"], "moon": ["regular"], "play": ["fill"], "sign-out": ["regular"], "sun": ["regular"],
  "target": ["regular"], "trophy": ["fill"], "warning-circle": ["regular"], "x": ["regular"], "bluetooth": ["regular"],
  "cube": ["regular"], "users-three": ["regular"], "calendar-blank": ["regular"], "robot": ["regular"], "upload-simple": ["regular"],
  "sparkle": ["fill"], "trend-down": ["regular"], "trend-up": ["regular"], "timer": ["regular"], "device-mobile": ["regular"],
  "file-csv": ["regular"], "lock-simple": ["regular"], "ranking": ["regular"], "waveform": ["regular"], "info": ["regular"],
  "seal-check": ["regular"], "terminal-window": ["regular"], "sliders-horizontal": ["regular"], "book-open": ["regular"],
  "racquet": ["regular"], "bluetooth-connected": ["regular"], "arrow-clockwise": ["regular"], "crosshair": ["regular"],
};

const pkg = new URL("../node_modules/@phosphor-icons/core/", import.meta.url).pathname; // the package exports no package.json
const version = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8")).version;
const out = {};
for (const [name, weights] of Object.entries(ICONS)) {
  for (const w of weights) {
    const file = join(pkg, "assets", w, w === "regular" ? `${name}.svg` : `${name}-${w}.svg`);
    const svg = readFileSync(file, "utf8");
    if (!svg.includes('viewBox="0 0 256 256"')) throw new Error(`${file}: unexpected viewBox`);
    const shapes = svg.match(/<(?!svg|\/)[a-z]+/g) ?? [];
    if (shapes.some((t) => t !== "<path")) throw new Error(`${file}: only <path> is supported, found ${shapes}`);
    out[w === "regular" ? name : `${name}-${w}`] = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
  }
}
const body = Object.entries(out).map(([k, ds]) => `  ${JSON.stringify(k)}: ${JSON.stringify(ds)},`).join("\n");
writeFileSync(new URL("../src/icons.gen.ts", import.meta.url), `// Generated by scripts/phosphor-icons.mjs from @phosphor-icons/core ${version} (MIT, https://phosphoricons.com). Do not edit.

export const PHOSPHOR = {
${body}
} as const satisfies Record<string, readonly string[]>;
`);
console.log(`icons.gen.ts: ${Object.keys(out).length} icons from @phosphor-icons/core ${version}`);
